"""Exercise a real local HTTPS subprocess using explicit certificate trust."""

from __future__ import annotations

import argparse
import getpass
import json
import re
import ssl
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

import httpx

from cloudsecops_live.workspace_config import load_config


def run_smoke(
    config_path: Path, username: str, password: str, *, expected_case_id: str | None = None
) -> dict[str, Any]:
    """Secrets travel through Python memory and TLS only, never process arguments."""
    config = load_config(config_path)
    trust = ssl.create_default_context(cafile=str(config.certificate))
    command = [
        sys.executable,
        "-m",
        "cloudsecops_live",
        "workspace",
        "serve",
        "--config",
        str(config_path.absolute()),
    ]
    process = subprocess.Popen(command, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        with httpx.Client(
            verify=trust, trust_env=False, timeout=3, follow_redirects=False
        ) as client:
            deadline = time.monotonic() + 30
            while True:
                if process.poll() is not None:
                    raise RuntimeError("https_server_unavailable")
                try:
                    response = client.get(config.origin + "/login")
                    break
                except httpx.TransportError:
                    if time.monotonic() >= deadline:
                        raise RuntimeError("https_server_unavailable") from None
                    time.sleep(0.1)
            if response.status_code != 200:
                raise RuntimeError("https_login_unavailable")
            # The single hidden challenge is generated by the trusted local app.
            fields = dict(re.findall(r'name="([a-z_]+)" value="([A-Za-z0-9_.-]+)"', response.text))
            response = client.post(
                config.origin + "/login",
                data={**fields, "username": username, "password": password},
                headers={"Origin": config.origin},
            )
            if response.status_code not in {302, 303}:
                raise RuntimeError("https_login_failed")
            response = client.get(config.origin + "/cases")
            if response.status_code != 200:
                raise RuntimeError("https_authenticated_read_failed")
            if expected_case_id is not None:
                if (
                    not re.fullmatch(r"[a-zA-Z0-9_-]{1,128}", expected_case_id)
                    or f'href="/cases/{expected_case_id}"' not in response.text
                ):
                    raise RuntimeError("https_assigned_case_missing")
                detail = client.get(config.origin + "/cases/" + expected_case_id)
                if detail.status_code != 200:
                    raise RuntimeError("https_assigned_case_read_failed")
            if not any(cookie.secure for cookie in client.cookies.jar):
                raise RuntimeError("https_secure_cookie_required")
            return {
                "https": True,
                "certificate_verified": True,
                "login": True,
                "authenticated_read": True,
                "secrets_in_receipt": False,
            }
    finally:
        process.terminate()
        try:
            process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=5)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--username", required=True)
    options = parser.parse_args()
    try:
        result = run_smoke(options.config, options.username, getpass.getpass("Password: "))
        print(json.dumps(result, sort_keys=True))
        return 0
    except (OSError, ValueError, RuntimeError, httpx.HTTPError):
        print('{"error":"https_smoke_failed"}', file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
